NOTDEF = (0x7F, 0x41, 0x41, 0x41, 0x7F)   # hollow box

# Double-striking would fill the 1-pixel gaps of these letters into a solid block, so Bold has its own,
# 7-column shapes for them.
BOLD_OVERRIDES = {
    "m": (0x7C, 0x7C, 0x04, 0x78, 0x04, 0x7C, 0x7C),
    "w": (0x3C, 0x7C, 0x40, 0x30, 0x40, 0x7C, 0x3C),
    "M": (0x7F, 0x7F, 0x06, 0x18, 0x06, 0x7F, 0x7F),
}


def glyph(cols, bold, override=None):
    """TrueType glyph + advance for one 5-column bitmap. Bold = every pixel also lights the pixel to its right."""
    if override:
        cols = list(override)
    elif bold:
        cols = [(cols[i] if i < 5 else 0) | (cols[i - 1] if i > 0 else 0) for i in range(6)]
    pen = TTGlyphPen(None)
    n = len(cols)
    for row in range(8):
        top = 700 - PX * row
        x = 0
        while x < n:
            if (cols[x] >> row) & 1:
                start = x
                while x < n and (cols[x] >> row) & 1:
                    x += 1
                # clockwise outline: bottom-left, top-left, top-right, bottom-right
                pen.moveTo((start * PX, top - PX))
                pen.lineTo((start * PX, top))
                pen.lineTo((x * PX, top))
                pen.lineTo((x * PX, top - PX))
                pen.closePath()
            else:
                x += 1
    lit = [i for i, c in enumerate(cols) if c]
    lsb = lit[0] * PX if lit else 0
    return pen.glyph(), (n + 1) * PX, lsb


def build(path, bold):
    style = "Bold" if bold else "Regular"
    order, cmap, glyphs, metrics = [".notdef"], {}, {}, {}

    g, adv, lsb = glyph(NOTDEF, bold)
    glyphs[".notdef"], metrics[".notdef"] = g, (adv, lsb)
    for ch, cols in GLYPHS.items():
        name = "uni%04X" % ord(ch)
        g, adv, lsb = glyph(cols, bold, BOLD_OVERRIDES.get(ch) if bold else None)
        order.append(name)
        cmap[ord(ch)] = name
        glyphs[name], metrics[name] = g, (adv, lsb)

    fb = FontBuilder(UPM, isTTF=True)
    fb.setupGlyphOrder(order)
    fb.setupCharacterMap(cmap)
    fb.setupGlyf(glyphs)
    fb.setupHorizontalMetrics(metrics)
    fb.setupHorizontalHeader(ascent=ASCENT, descent=-DESCENT)
    fb.setupNameTable({
        "familyName": "iTaleem Pixel",
        "styleName": style,
        "uniqueFontIdentifier": "iTaleemPixel-%s-1.0" % style,
        "fullName": "iTaleem Pixel %s" % style,
        "psName": "ITaleemPixel-%s" % style,
        "version": "Version 1.0",
    })
    fb.setupOS2(
        sTypoAscender=ASCENT, sTypoDescender=-DESCENT, sTypoLineGap=0,
        usWinAscent=ASCENT, usWinDescent=DESCENT,
        usWeightClass=700 if bold else 400,
        fsSelection=0x20 if bold else 0x40,
        sxHeight=500, sCapHeight=700,
        xAvgCharWidth=600, fsType=0,
    )
    fb.setupPost(isFixedPitch=0)
    fb.font["head"].macStyle = 1 if bold else 0
    fb.save(path)
    print("wrote", path)


if __name__ == "__main__":
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "Fonts")
    os.makedirs(out, exist_ok=True)
    build(os.path.join(out, "ITaleemPixel-Regular.ttf"), bold=False)
    build(os.path.join(out, "ITaleemPixel-Bold.ttf"), bold=True)
