#!/usr/bin/env python3
"""Builds the "iTaleem Pixel" fonts (Regular + Bold) used by the Retro theme.

The letter shapes are the classic 5x7 dot-matrix patterns (like old arcade / console text), one byte per
column, bit 0 = top row. Bit 7 is a descender row below the baseline (g j p q y , ;). Every lit pixel is
drawn as a square, so the fonts are real outline TrueType fonts that scale to any size.

    python3 Tools/make_pixel_font.py          # writes Fonts/ITaleemPixel-Regular.ttf and -Bold.ttf

Needs fontTools (pip install fonttools). The generated .ttf files are committed, so this only has to be
run again after changing the glyph table below.
"""
