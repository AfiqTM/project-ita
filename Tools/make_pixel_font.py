from fontTools.pens.ttGlyphPen import TTGlyphPen

PX = 100          # font units per pixel
UPM = 800         # 8 rows of pixels = 1 em, so a font size of 8 x N points gives N-point pixels
ASCENT, DESCENT = 800, 200

